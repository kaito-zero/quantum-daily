"""
Day 1: 첫 양자 회로

목표
  큐비트 1개를 '중첩' 상태로 만들고, 측정하면 0과 1이 반반 나오는지 확인한다.

흐름
  1. 큐비트는 항상 [1, 0](무조건 0이 나오는 설정)에서 시작한다. 이름은 |0>.
  2. H(아다마르) 게이트를 걸면 상태가 [1/√2, 1/√2]가 된다. (1/√2 = 0.7071...)
     0과 1 양쪽에 같은 비중이 걸린 '중첩' 상태다.
  3. 측정하면 0 또는 1 중 하나만 나온다.
     각각 나올 확률 = 숫자의 제곱 = (1/√2) x (1/√2) = 1/2 = 정확히 50%
  4. 한 번 측정해서는 확률을 알 수 없으니, 같은 회로를 1,000번 돌려 비율을 본다.

예상 결과
  {'0': 500 근처, '1': 500 근처}
"""

# QuantumCircuit: 양자 회로를 만드는 클래스.
# 회로 = 큐비트에 어떤 게이트를 어떤 순서로 걸지 적은 할 일 목록.
from qiskit import QuantumCircuit

# AerSimulator: 내 PC에서 양자컴퓨터를 흉내 내는 시뮬레이터.
# 실제 양자컴퓨터가 아니라 일반 컴퓨터로 계산하므로 노이즈 없는 이상적인 결과가 나온다.
from qiskit_aer import AerSimulator

# 빈 회로를 만든다. 큐비트 개수: 1개, 측정 결과 적어 둘 곳(고전 비트): 1개
#   번호는 0부터 센다. 큐비트가 1개면 0번 하나뿐이다.
#   만약 QuantumCircuit(5, 1)이었으면 큐비트는 0, 1, 2, 3, 4번이고
#   qc.h(0) ~ qc.h(4)까지 가능하다.
qc = QuantumCircuit(1, 1)

# 큐비트는 항상 [1, 0]에서 시작한다.
#   이유: 계산하려면 출발점이 확실해야 해서. 모두가 그렇게 약속했다.
# qc.h(0): '0번 큐비트에 H 게이트를 건다'를 할 일 목록에 추가한다.
#   H의 규칙: [a, b] -> [(a + b)/√2, (a - b)/√2]
#   [1, 0]에 걸면 [1/√2, 1/√2], 즉 정확히 반반인 설정이 된다. (다이얼을 50:50으로 돌린다)
#   (0.707은 1/√2를 줄여 쓴 값이라 제곱하면 0.4998로 살짝 모자란다)
qc.h(0)
#qc.h(0)
#qc.x(0)
#qc.ry(1.8546,0)

# '0번 큐비트를 측정해서 결과를 0번 고전 비트에 적는다'를 할 일 목록에 추가한다.
# 측정하는 순간 0 또는 1로 확정된다. (뽑기 한 번)
qc.measure(0, 0)

# 시뮬레이터를 만들고, 회로를 1,000번 실행한다(shots=1000).
# 할 일 목록이 실제로 수행되는 곳은 여기다.
simulator = AerSimulator()
job = simulator.run(qc, shots=1000)


# 실행이 끝나면 결과를 받아서, 0과 1이 각각 몇 번 나왔는지 센다.
result = job.result()
counts = result.get_counts()   # 예: {'0': 480, '1': 520}

print(counts)
print(qc.draw())   # 회로를 글자 그림으로 출력

# 직접 실험해 본 결과 (shots=1000)
#   1. qc.h(0) 줄을 지우고 돌리면? -> 1,000번 모두 0.             검증 완료 {'0': 1000}
#   2. qc.h(0) 한 개 넣고 돌리면? -> 반반 근처.                   검증 완료 {'1': 503, '0': 497}
#   3. qc.h(0) 을 두 줄 연속으로 쓰면? -> 1,000번 모두 0.         검증 완료 {'0': 1000}
#      동전을 두 번 던진 것과 결과가 다르다. H의 규칙에 [1/√2, 1/√2]를 넣어 계산해 보면 이유가 보인다.
#   4. qc.h(0) 대신 qc.x(0) 을 쓰면? -> [0, 1]로 뒤집혀 1,000번 모두 1.  검증 완료 {'1': 1000}
#   5. qc.h(0) 대신 qc.ry(1.8546, 0) 을 쓰면? -> [0.6, 0.8]이 되어
#      0이 36%, 1이 64% 근처.                                   검증 완료 {'1': 639, '0': 361}