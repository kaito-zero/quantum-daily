"""
Day 4: 측정과 보른 규칙

목표
  측정 결과의 확률을 진폭에서 직접 계산해 보고(보른 규칙), 측정이 상태를 바꾼다는 것을 확인한다.

흐름
  1. 보른 규칙: 상태 [a, b]를 측정하면 0이 나올 확률은 |a|², 1이 나올 확률은 |b|² 이다.
     |a|는 a의 크기다. 진폭이 음수든 복소수든 크기만 본다.
  2. 손으로 계산한 확률과 1,000번 측정한 결과를 비교한다. 딱 맞지는 않고 근처에 온다.
  3. 측정 횟수를 늘릴수록 비율이 확률에 가까워진다. 확률은 '많이 뽑았을 때의 비율'이다.
  4. 측정하면 상태가 바뀐다. 0이 나왔으면 그 순간부터 상태는 |0>, 1이 나왔으면 |1>이다.
     그래서 바로 다시 측정하면 항상 같은 값이 나온다.
  5. 중간에 측정하면 간섭이 사라진다. H - H는 항상 0인데, H - 측정 - H는 반반이 된다.

예상 결과
  측정이 들어간 줄은 실행할 때마다 숫자가 조금씩 달라진다. 주석의 숫자는 예시다.
"""

import numpy as np

from qiskit import QuantumCircuit
from qiskit.quantum_info import Statevector
from qiskit_aer import AerSimulator


def show(v):
    """벡터를 [0.6, 0.8]처럼 보기 좋게 적어 주는 도우미. 소수 셋째 자리까지만 적는다."""
    out = []
    for x in np.asarray(v, dtype=complex):
        re = round(x.real, 3) + 0.0   # + 0.0 은 -0.0 을 0.0 으로 바꾼다
        im = round(x.imag, 3) + 0.0
        if im == 0:
            out.append(f"{re:g}")
        elif re == 0:
            out.append(f"{im:g}j")
        else:
            out.append(f"{re:g}{im:+g}j")
    return "[" + ", ".join(out) + "]"


def born(state):
    """보른 규칙. 상태 벡터를 받아 [0이 나올 확률, 1이 나올 확률]을 돌려준다."""
    return np.abs(np.asarray(state)) ** 2   # 진폭 하나하나의 크기를 제곱한다


# ---------------------------------------------------------------
# 1. 보른 규칙: 확률을 손으로 계산하기
# ---------------------------------------------------------------
examples = [
    np.array([0.8, 0.6]),              # 실수 진폭. 0.8 x 0.8 = 0.64, 0.6 x 0.6 = 0.36
    np.array([0.6, -0.8]),             # 음수 진폭. 부호는 확률에 영향이 없다
    np.array([0.6, 0.8j]),             # 복소수 진폭. 0.8j의 크기는 0.8이다
    np.array([1, 1j]) / np.sqrt(2),    # 반반인 상태
]
for s in examples:
    p = born(s)
    print("1.", show(s), "-> 확률", show(p), "합:", round(float(p.sum()), 3))

# ---------------------------------------------------------------
# 2. 계산한 확률과 1,000번 측정한 결과 비교하기
# ---------------------------------------------------------------
state = np.array([0.6, 0.8j])
p0, p1 = born(state)                                   # 0.36, 0.64
expected = round(1000 * p1)                            # 1,000번 중 1이 나올 횟수의 예상값: 640
counts = Statevector(state).sample_counts(1000)        # 1,000번 측정한 것처럼 결과를 뽑는다
ones = int(counts.get("1", 0))                         # 1이 나온 횟수. 한 번도 안 나왔으면 0
print(f"2. 계산: 1,000번 중 1이 {expected}번 근처")
print(f"   실제: {ones}번 (차이 {abs(ones - expected)}번)")
# 보통 15번 안팎으로 벗어나고, 가끔은 30번 넘게 벗어난다. 뽑기가 랜덤이기 때문이다.

# ---------------------------------------------------------------
# 3. 많이 뽑을수록 비율이 확률에 가까워진다
# ---------------------------------------------------------------
for shots in (10, 100, 1000, 10000, 100000):
    counts = Statevector(state).sample_counts(shots)
    ones = int(counts.get("1", 0))
    print(f"3. {shots:>6}번 측정 -> 1의 비율 {ones / shots:.4f} (확률 {p1:.2f})")
# 10번만 뽑으면 0.4나 0.9도 나온다. 100,000번이면 0.64에서 거의 벗어나지 않는다.

# ---------------------------------------------------------------
# 4. 측정하면 상태가 바뀐다
# ---------------------------------------------------------------
plus = Statevector.from_label("+")       # |+> = [0.707, 0.707]. 측정하면 0과 1이 반반
outcome, after = plus.measure()          # measure()는 (측정 결과, 측정 뒤의 상태)를 돌려준다
print("4. |+>를 측정한 결과:", outcome, "-> 측정 뒤의 상태:", show(after.data))
outcome2, after2 = after.measure()       # 같은 큐비트를 바로 다시 측정한다
print("   다시 측정한 결과:", outcome2, "-> 상태:", show(after2.data))
# 처음에 0이 나왔으면 상태가 [1, 0]으로, 1이 나왔으면 [0, 1]로 바뀐다.
# 그래서 다시 측정한 결과는 항상 처음과 같다. 측정 전의 [0.707, 0.707]은 남아 있지 않다.

# 회로로도 확인한다. 같은 큐비트를 연달아 두 번 측정하고 결과를 칸 두 개에 따로 적는다.
qc = QuantumCircuit(1, 2)    # 큐비트 1개, 결과 적는 칸 2개
qc.h(0)
qc.measure(0, 0)             # 첫 번째 측정 결과 -> 0번 칸
qc.measure(0, 1)             # 두 번째 측정 결과 -> 1번 칸
counts = AerSimulator().run(qc, shots=1000).result().get_counts()
print("   연달아 두 번 측정:", counts)        # 예: {'00': 510, '11': 490}
# 결과 문자열은 오른쪽이 0번 칸이다. '11'은 두 번 다 1, '00'은 두 번 다 0.
# 두 측정이 엇갈리는 '01'과 '10'은 한 번도 나오지 않는다.

# ---------------------------------------------------------------
# 5. 중간에 측정하면 간섭이 사라진다
# ---------------------------------------------------------------
sim = AerSimulator()

no_peek = QuantumCircuit(1, 1)
no_peek.h(0)
no_peek.h(0)
no_peek.measure(0, 0)
print("5. H - H - 측정:", sim.run(no_peek, shots=1000).result().get_counts())            # {'0': 1000}

peek = QuantumCircuit(1, 1)
peek.h(0)
peek.measure(0, 0)           # 가운데에서 측정한다. 이 순간 상태가 |0> 아니면 |1>로 정해진다
peek.h(0)
peek.measure(0, 0)           # 마지막 측정 결과가 같은 칸에 덮어써진다
print("   H - 측정 - H - 측정:", sim.run(peek, shots=1000).result().get_counts())        # 예: {'0': 498, '1': 502}
# 가운데에서 측정하지 않으면 두 갈래가 서로 지워져 0만 남는다(Day 1, 2의 간섭).
# 가운데에서 측정하면 갈래가 하나로 정해져서 지워질 것이 없고, 결과는 반반이 된다.
