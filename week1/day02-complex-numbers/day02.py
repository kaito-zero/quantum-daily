"""
Day 2: 복소수 - 크기와 위상

목표
  큐비트의 숫자가 '양수/음수'를 넘어, 방향을 가진 화살표(복소수)가 될 수 있다는 것을 이해한다.

흐름
  1. 복소수는 숫자 두 개(실수부, 허수부)로 된 수다. 화살표로 그리면 가로와 세로다.
  2. 크기 = 화살표의 길이. 위상 = 화살표의 방향(각도).
  3. 켤레 = 세로 방향을 뒤집은 수. 복소수 x 켤레 = 크기의 제곱.
  4. e^(iθ)는 길이 1, 각도 θ인 화살표다. 곱하면 길이는 그대로고 θ만큼 돈다.
  5. 큐비트에서 확률 = 숫자의 '크기'를 제곱한 값이다. (어제의 '제곱'을 정확히 말하면 이것)
     위상은 측정에 보이지 않지만, 다음 게이트의 결과를 바꾼다.
"""

import cmath   # 복소수용 수학 함수 (phase, exp)
import math

from qiskit import QuantumCircuit
from qiskit_aer import AerSimulator

# ---------------------------------------------------------------
# 1. 복소수를 만들고 크기와 위상 재기
# ---------------------------------------------------------------
# 파이썬에서는 허수부 뒤에 j를 붙인다. 3 + 4j = 가로 3, 세로 4인 화살표.
z = 3 + 4j
print("1. 복소수:", z)
print("   실수부(가로):", z.real)
print("   허수부(세로):", z.imag)
print("   크기(길이):", abs(z))                                        # 5.0
print("   위상(각도):", round(math.degrees(cmath.phase(z)), 2), "도")   # 53.13도

# i(파이썬의 1j)는 '90도 회전'이다. 두 번 곱하면 180도 회전 = -1.
print("   i x i =", 1j * 1j)                                           # (-1+0j)

# ---------------------------------------------------------------
# 2. 켤레: 허수부(세로)의 부호를 뒤집은 수
# ---------------------------------------------------------------
print("2. 켤레:", z.conjugate())                                       # (3-4j)
# 복소수에 자기 켤레를 곱하면 크기의 제곱이 된다. 5 x 5 = 25
print("   z x 켤레 =", z * z.conjugate())                              # (25+0j)

# ---------------------------------------------------------------
# 3. 오일러 공식: e^(iθ) = 길이 1, 각도 θ인 화살표
#    어떤 복소수에 곱하면 길이는 그대로 두고 θ만큼 돌린다.
# ---------------------------------------------------------------
theta = math.radians(90)        # 90도를 라디안으로 바꾼다
r = cmath.exp(1j * theta)       # e^(i x 90도). 사실상 i와 같다
w = z * r                       # z를 90도 돌린다
print("3. e^(i x 90도)의 크기:", abs(r))                               # 1.0
print("   돌린 결과:", complex(round(w.real, 6), round(w.imag, 6)))    # (-4+3j)
print("   크기:", abs(w))                                              # 5.0 그대로
print("   위상:", round(math.degrees(cmath.phase(w)), 2), "도")        # 143.13도 = 53.13 + 90

# 어제의 '부호 뒤집기(-1 곱하기)'는 180도 회전이다.
m = cmath.exp(1j * math.pi)
print("   e^(i x 180도) =", complex(round(m.real, 6), round(m.imag, 6)))   # (-1+0j)

# ---------------------------------------------------------------
# 4. 큐비트에 적용
# ---------------------------------------------------------------
# 상태의 숫자가 복소수여도 확률 규칙은 같다. 확률 = 크기의 제곱.
state = [1 / math.sqrt(2), 1j / math.sqrt(2)]      # [0.707, 0.707i]
probs = [round(abs(x) ** 2, 3) for x in state]
print("4. 상태 [0.707, 0.707i]의 확률:", probs)                        # [0.5, 0.5]

# 실험: H - P(각도) - H
#   qc.p(각도, 0)은 둘째 숫자에 e^(i x 각도)를 곱한다. 둘째 숫자의 화살표만 돌리는 게이트다.
#   H 다음에 바로 측정하면 각도가 몇이든 반반이다. (위상은 측정에 안 보인다)
#   그런데 H를 한 번 더 걸면 각도에 따라 결과가 달라진다.
simulator = AerSimulator()
for deg in (0, 60, 90, 180):
    qc = QuantumCircuit(1, 1)
    qc.h(0)
    qc.p(math.radians(deg), 0)
    qc.h(0)
    qc.measure(0, 0)
    counts = simulator.run(qc, shots=1000).result().get_counts()
    print(f"   H - P({deg}도) - H ->", counts)
# 예상: 0도면 0만, 180도면 1만(어제의 H-Z-H와 같다), 90도면 반반, 60도면 1이 25% 근처.