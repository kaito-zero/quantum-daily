"""
Day 3: 상태 벡터와 디랙 표기법

목표
  큐비트의 상태를 '벡터'로 적는 법과, 그 벡터에 이름을 붙이는 디랙 표기법(|0>, |1>)을 익힌다.

흐름
  1. 확률 벡터: 동전 같은 보통의 뽑기는 [0이 나올 확률, 1이 나올 확률]로 적는다. 두 숫자의 합이 1이다.
  2. 상태 벡터: 큐비트는 [a, b]로 적는다. a, b는 '진폭'이고, 진폭의 크기를 제곱해야 확률이 된다.
     확률이 같아도 진폭의 부호나 방향이 다르면 다른 상태다. 확률 벡터로는 이 차이를 적을 수 없다.
  3. 디랙 표기법: |0> = [1, 0], |1> = [0, 1]. 모든 상태는 a|0> + b|1> 로 쓸 수 있다.
     자주 쓰는 상태에는 이름이 있다. |+> = [0.707, 0.707], |-> = [0.707, -0.707]
  4. 정규화: 상태 벡터는 '크기를 제곱한 값의 합'이 1이어야 한다. 아니면 벡터를 자기 길이로 나눠서 맞춘다.
  5. Qiskit의 Statevector로 같은 내용을 확인한다. 측정하지 않고도 상태 벡터를 직접 들여다볼 수 있다.

예상 결과
  맨 마지막 줄(1,000번 측정)만 실행할 때마다 조금씩 달라지고, 나머지는 항상 같다.
"""

import numpy as np   # 벡터 계산용 라이브러리. Qiskit을 설치할 때 같이 설치된다

from qiskit import QuantumCircuit
from qiskit.quantum_info import Statevector


def show(v):
    """벡터를 [0.6, 0.8]처럼 보기 좋게 적어 주는 도우미. 소수 셋째 자리까지만 적는다."""
    out = []
    for x in np.asarray(v, dtype=complex):
        re = round(x.real, 3) + 0.0   # + 0.0 은 -0.0 을 0.0 으로 바꾼다
        im = round(x.imag, 3) + 0.0
        if im == 0:
            out.append(f"{re:g}")          # 허수부가 0이면 실수처럼 적는다
        elif re == 0:
            out.append(f"{im:g}j")
        else:
            out.append(f"{re:g}{im:+g}j")
    return "[" + ", ".join(out) + "]"


# ---------------------------------------------------------------
# 1. 확률 벡터: 보통의 뽑기를 숫자 두 개로 적기
# ---------------------------------------------------------------
# np.array([...])는 숫자 여러 개를 묶은 벡터를 만든다. JS의 배열과 비슷하지만 통째로 계산할 수 있다.
coin = np.array([0.5, 0.5])        # 공정한 동전: 0이 50%, 1이 50%
biased = np.array([0.36, 0.64])    # 1이 더 자주 나오는 뽑기
print("1. 공정한 동전:", show(coin), "합:", coin.sum())
print("   치우친 뽑기:", show(biased), "합:", biased.sum())
# 확률 벡터의 규칙: 모든 숫자가 0 이상이고, 합이 1이다.

# ---------------------------------------------------------------
# 2. 상태 벡터: 큐비트는 확률 대신 '진폭'을 적는다
# ---------------------------------------------------------------
state = np.array([0.6, 0.8])
probs = np.abs(state) ** 2          # 진폭의 크기를 제곱하면 확률. np.abs는 Day 2의 abs와 같다
print("2. 상태 벡터:", show(state))
print("   확률:", show(probs), "합:", round(float(probs.sum()), 3))

# 확률은 전부 [0.36, 0.64]로 같지만 서로 다른 상태 세 개.
# 확률 벡터로 적으면 셋이 똑같아 보인다. 상태 벡터로 적어야 구분된다.
for s in (np.array([0.6, 0.8]), np.array([0.6, -0.8]), np.array([0.6, 0.8j])):
    print("  ", show(s), "-> 확률", show(np.abs(s) ** 2))

# ---------------------------------------------------------------
# 3. 디랙 표기법: 벡터에 이름표 붙이기
# ---------------------------------------------------------------
ket0 = np.array([1, 0])   # |0> : 측정하면 항상 0
ket1 = np.array([0, 1])   # |1> : 측정하면 항상 1

# 모든 상태는 |0>과 |1>을 진폭만큼 섞은 것이다. 벡터에 숫자를 곱하고 더하면 된다.
psi = 0.6 * ket0 + 0.8 * ket1          # 0.6|0> + 0.8|1>
print("3. 0.6|0> + 0.8|1> =", show(psi))

# 자주 쓰는 상태에는 이름이 있다.
plus = (ket0 + ket1) / np.sqrt(2)      # |+> : |0>에 H를 건 상태
minus = (ket0 - ket1) / np.sqrt(2)     # |-> : |1>에 H를 건 상태
print("   |+> =", show(plus))
print("   |-> =", show(minus))

# ---------------------------------------------------------------
# 4. 정규화: 길이를 1로 맞추기
# ---------------------------------------------------------------
# [3, 4]는 상태가 아니다. 제곱의 합이 9 + 16 = 25라서 '확률의 합이 1'이 안 된다.
v = np.array([3, 4])
length = np.linalg.norm(v)             # 벡터의 길이. sqrt(3*3 + 4*4) = 5
unit = v / length                      # 길이로 나누면 방향은 그대로고 길이만 1이 된다
print("4. [3, 4]의 길이:", length)
print("   정규화한 벡터:", show(unit), "-> 제곱의 합:", round(float(np.sum(np.abs(unit) ** 2)), 3))

# 복소수가 들어 있어도 방법은 같다.
w = np.array([1, 1j])
print("   [1, 1j]를 정규화:", show(w / np.linalg.norm(w)))

# ---------------------------------------------------------------
# 5. Qiskit의 Statevector로 확인하기
# ---------------------------------------------------------------
# Statevector.from_label("0")은 |0>을 만든다. "1", "+", "-"도 쓸 수 있다.
print("5. |0> =", show(Statevector.from_label("0").data))
plus_sv = Statevector.from_label("+")
print("   |+> =", show(plus_sv.data), "확률:", show(plus_sv.probabilities()))

# is_valid()는 '제곱의 합이 1인가', 즉 상태가 될 수 있는 벡터인가를 알려 준다.
print("   [0.6, 0.8]은 상태인가?", Statevector([0.6, 0.8]).is_valid())   # True
print("   [3, 4]는 상태인가?", Statevector([3, 4]).is_valid())           # False

# 회로를 Statevector에 넣으면, 측정하지 않고 '지금 상태 벡터'를 볼 수 있다.
# 실제 양자컴퓨터에서는 불가능하고 시뮬레이터라서 되는 일이다.
qc = QuantumCircuit(1)
qc.h(0)
print("   H를 건 뒤:", show(Statevector(qc).data))        # |+>
qc.z(0)
print("   H, Z를 건 뒤:", show(Statevector(qc).data))     # |->

# sample_counts(1000)은 그 상태를 1,000번 측정한 것처럼 결과를 뽑아 준다.
counts = Statevector([0.6, 0.8]).sample_counts(1000)
counts = {str(k): int(n) for k, n in counts.items()}      # 평범한 dict로 바꿔서 보기 좋게 출력한다
print("   [0.6, 0.8]을 1,000번 측정:", counts)             # 예: {'0': 360 근처, '1': 640 근처}
